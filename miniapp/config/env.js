/**
 * 小程序环境配置（单一事实源）
 *
 * ⭐ 为什么要独立成文件
 * ------------------
 * 上线必改服务器地址。此前 BASE_URL 硬编码在 utils/api.js 里，
 * 改地址要翻代码找 —— 而漏改的后果是「开发者工具一切正常、
 * 真机全挂」（127.0.0.1 在手机上指的是手机自己）。
 *
 * 现在：改这一个文件 → 微信开发者工具里「详情 → 本地设置 →
 * 不校验合法域名」勾上，开发者工具与真机都走同一份配置。
 *
 * ⚠️ 上线前务必把 BASE_URL 改成 https://<你的已备案域名>
 *    微信正式版会强制校验合法域名，指向 127.0.0.1 一定失败。
 */

// ── 服务地址 ──────────────────────────────────────────────────
// 开发期：微信开发者工具勾「不校验合法域名」后用本机回环；
//        真机预览请用 adb reverse tcp:8080 tcp:8080，或填局域网 IP。
// 生产：  改成已备案域名的 https 地址。
const BASE_URL = 'http://127.0.0.1:8080';

// ── 合法域名清单（小程序后台「开发-开发设置-服务器域名」要配的）──
// 填的时候参照这个表，三类域名分开配：
//   request 合法域名    → API 调用
//   uploadFile 合法域名 → PDF 工具上传文件
//   downloadFile 合法域名 → 图片/视频/音频下载
// ⚠️ 微信限制：每个合法域名最多 1 个端口，且不配端口时请求 URL 里
//    也不能带端口（含默认 443）。所以下面用标准 https 无端口。
const DOMAIN_HINT = {
  request: 'https://<你的域名>',
  uploadFile: 'https://<你的域名>',
  downloadFile: 'https://<你的域名>',
};

// ── 超时 ──────────────────────────────────────────────────────
// 单条 30s；批量是服务端串行解析（2C2G），5 条可能 10s+ → 60s
const TIMEOUT = 30000;
const TIMEOUT_BATCH = 60000;

module.exports = {
  BASE_URL,
  DOMAIN_HINT,
  TIMEOUT,
  TIMEOUT_BATCH,
};
